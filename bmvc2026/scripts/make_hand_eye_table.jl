#=
make_hand_eye_table.jl — the supplement's hand-eye diagnostics table
(tab:handeye) and its prose macros, generated from the hand-eye calibrations
that make_hand_eye.jl writes into the keyed hand_eye-<key>/ of the
evaluation's sources (src/runs.jl `hand_eye_dir`). Nothing in the table or the
prose that echoes it is typed by hand.

Writes:
  plotsdir()/handeye_table.tex   the tabular (\input by bmvc_supp.tex)
  plotsdir()/handeye_stats.tex   \newcommand macros for the prose echoes:
      \bbHeFrames  \bbHeRecovered  \bbHeResidTransMM  \bbHeResidRotDeg  \bbHeMarkers
      \aprHe*  \ucoHe*   (same fields per system)

The residual columns are the noise scale the staged linear fit reports:
`sigma_trans_mm` (mm) and `sigma_rot_rad` (rendered in degrees). The pre-0.6.2
table also carried a variance factor s^2 and a per-parameter 1σ on X; those came
from an RVG fit object the current `hand_eye` deliberately does not retain
(src/calibration.jl, "scalars only"), so the table now reports exactly the
scalars the pipeline computes rather than numbers no run can reproduce.

Run AFTER make_hand_eye.jl (regenerate_paper.jl orders them).
  julia --startup-file=no --project=bmvc2026 bmvc2026/scripts/make_hand_eye_table.jl
Config of record: configs/figures/evaluation.toml.
=#
# reproduce: reads configs/figures/evaluation.toml

using DrWatson
@quickactivate

import JSON3
using Printf: @sprintf

if !isdefined(Main, :BlobBoardsEval)
    include(joinpath(@__DIR__, "..", "src", "BlobBoardsEval.jl"))
end
using Main.BlobBoardsEval: eval_sources, hand_eye_dir, figure_config, write_figure_records
using VisualGeometryEval.Experiments: Stage, run_stages
using DrWatson: projectdir

const EVAL, EVAL_PATH = figure_config("evaluation"; default = projectdir("configs", "figures", "evaluation.toml"))
const DRV = EVAL["drivers"]
const CALIB = hand_eye_dir(eval_sources(EVAL))

# (display name, hand_eye json stem, macro prefix), in table row order.
const SYSTEMS = [
    ("BlobBoards", "bb", "bb"),
    ("AprilTag", "apriltags", "apr"),
    ("ArUco", "aruco", "uco"),
]

_meta(stem) = JSON3.read(read(joinpath(CALIB, "hand_eye_$(stem).json"), String)).provenance   # vgio/transforms/v3

rad2deg_(x) = x * 180 / pi

function main()
    rows = map(SYSTEMS) do (disp, stem, pfx)
        m = _meta(stem)
        (; disp, pfx,
         frames = Int(m.n_frames_used),
         recovered = Int(m.n_frames_recovered),
         markers = Int(m.n_markers),
         resid_mm = Float64(m.sigma_trans_mm),
         resid_deg = rad2deg_(Float64(m.sigma_rot_rad)))
    end

    # ---- table -------------------------------------------------------------------
    tbl = plotsdir("handeye_table.tex")
    open(tbl, "w") do io
        println(io, "% handeye_table.tex — generated by scripts/make_hand_eye_table.jl; do not edit by hand")
        println(io, "\\begin{tabular}{@{}lrrrr@{}}")
        println(io, "\\toprule")
        println(io, "system & frames & recovered & resid.\\ mm & resid.\\ deg \\\\")
        println(io, "\\midrule")
        for r in rows
            println(io, @sprintf("%s & \$%d\$ & \$%d\$ & \$%.2f\$ & \$%.3f\$ \\\\",
                                 r.disp, r.frames, r.recovered, r.resid_mm, r.resid_deg))
        end
        println(io, "\\bottomrule")
        println(io, "\\end{tabular}")
    end

    # ---- prose macros ------------------------------------------------------------
    stats = plotsdir("handeye_stats.tex")
    open(stats, "w") do io
        println(io, "% handeye_stats.tex — generated by scripts/make_hand_eye_table.jl; do not edit by hand")
        for r in rows
            P = uppercasefirst(r.pfx)
            println(io, "\\newcommand{\\$(r.pfx)HeFrames}{$(r.frames)}")
            println(io, "\\newcommand{\\$(r.pfx)HeRecovered}{$(r.recovered)}")
            println(io, "\\newcommand{\\$(r.pfx)HeMarkers}{$(r.markers)}")
            println(io, "\\newcommand{\\$(r.pfx)HeResidTransMM}{$(round(r.resid_mm; digits = 2))}")
            println(io, "\\newcommand{\\$(r.pfx)HeResidRotDeg}{$(round(r.resid_deg; digits = 3))}")
        end
    end

    println("handeye_table.tex + handeye_stats.tex -> $(plotsdir())")
    for r in rows
        println("  $(r.disp): $(r.frames) frames ($(r.recovered) rec), $(round(r.resid_mm; digits=2)) mm, $(round(r.resid_deg; digits=3))°")
    end
    write_figure_records(EVAL, EVAL_PATH; driver = "bmvc2026/scripts/make_hand_eye_table.jl", inputs = [CALIB], outputs = [tbl, stats])
    return nothing
end

run_stages("make_hand_eye_table", [Stage(:emit, "handeye_table.tex + handeye_stats.tex from the hand-eye records", () -> false, main)])
