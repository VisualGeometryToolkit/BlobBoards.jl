#=
make_detection_stats.jl — detection-count macros for the paper's identification
paragraph, generated from the BlobBoards detection run (found through its
config of record, evaluation.toml [runs] bb) so the prose can never quote a
stale count.

Writes plotsdir()/det_stats.tex with:

  \bbDetPoses      total poses BlobBoards returned across the evaluation set
  \bbDetCaptures   number of captures (frames) in the evaluation set
  \bbGalleryEval   distinct board identities in the evaluation gallery
  \bbMinSpacingMM  minimum centre-to-centre board spacing on the panel (mm),
                   the geometric floor a misidentification would have to exceed

The identification argument in the paper ("no reported detection is a
misidentification") pairs \bbDetPoses / \bbGalleryEval with the alignment
residual. The residual is a spatial-verification quantity that the pose JSON
does not carry; it is emitted separately by an instrumented run
(make_align_residual_stats.jl) rather than typed by hand — see that script.

Usage:
  julia --startup-file=no --project=bmvc2026 bmvc2026/scripts/make_detection_stats.jl
Config of record: configs/figures/evaluation.toml.
=#
# reproduce: reads configs/figures/evaluation.toml

using DrWatson
@quickactivate

import JSON3

if !isdefined(Main, :BlobBoardsEval)
    include(joinpath(@__DIR__, "..", "src", "BlobBoardsEval.jl"))
end
using Main.BlobBoardsEval: figure_config, write_figure_records, load_detected_poses, eval_sources, poses_dir
using VisualGeometryToolkitEval.Experiments: Stage, run_stages
using DrWatson: projectdir

const EVAL, EVAL_PATH = figure_config("evaluation"; default = projectdir("configs", "figures", "evaluation.toml"))
const DRV = EVAL["drivers"]
const SRC = eval_sources(EVAL)
const DATASET = SRC.inputs
const POSES = poses_dir(SRC, "bb")


# Minimum centre spacing is fixed panel geometry, but read it from the board
# layout rather than hardcoding, so a different panel can't silently keep the
# old number. The panel layout lives beside the images as a board-centres file;
# fall back to the documented 47.8 mm only if it is absent.
function _min_spacing_mm()
    for cand in (joinpath(DATASET, "panel_layout.json"),
                 joinpath(DATASET, "boards", "panel_layout.json"))
        isfile(cand) || continue
        c = JSON3.read(read(cand, String))
        pts = [(Float64(p.x), Float64(p.y)) for p in c.centres]
        d = minimum(hypot(a[1] - b[1], a[2] - b[2]) for a in pts, b in pts if a !== b)
        return round(d; digits = 1)
    end
    return 47.8   # documented panel minimum; no layout file present
end

function main()
    isdir(POSES) || error("BlobBoards detections not found at $POSES — run go_bmvc2026.jl first")
    # The run's detections (vgio/target_poses/v1): a frame per capture, a pose
    # per detected board.
    detected = load_detected_poses(POSES)
    n_captures = length(detected)
    n_poses = sum(length, values(detected); init = 0)
    ids = Set(p.id for ps in values(detected) for p in ps)

    out = plotsdir("det_stats.tex")
    open(out, "w") do io
        println(io, "% det_stats.tex — generated by scripts/make_detection_stats.jl")
        println(io, "% detection counts from the BlobBoards detection run; do not edit by hand")
        println(io, "\\newcommand{\\bbDetPoses}{$n_poses}")
        println(io, "\\newcommand{\\bbDetCaptures}{$(n_captures)}")
        println(io, "\\newcommand{\\bbGalleryEval}{$(length(ids))}")
        println(io, "\\newcommand{\\bbMinSpacingMM}{$(_min_spacing_mm())}")
    end
    println("det_stats.tex -> $out  ($(n_poses) poses, $(n_captures) captures, $(length(ids))-board gallery)")
    write_figure_records(EVAL, EVAL_PATH; driver = "bmvc2026/scripts/make_detection_stats.jl", inputs = [POSES], outputs = [out])
    return nothing
end

run_stages("make_detection_stats", [Stage(:emit, "det_stats.tex from the BlobBoards detections", () -> false, main)])
