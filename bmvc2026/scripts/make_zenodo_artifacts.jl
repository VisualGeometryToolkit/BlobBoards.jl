#=
make_zenodo_artifacts.jl — pack the published input tiers of bmvc2026 and bind
them in Artifacts.toml (the AUTHOR's step; consumers run scripts/fetch_data.jl).

  julia --project=bmvc2026 bmvc2026/scripts/make_zenodo_artifacts.jl --stage=<dir> \
        [--only=<tier>,…] [--record=<group>=<id>,…]

ONLY INPUTS are published: measured data and what no code of ours produces.
Every result (detections, motion-capture records, hand-eye fits, pose-error
cells, overlays) is regenerated by the stages of configs/reproduce.toml into
results_root() (src/runs.jl), so no tier carries one.

What each tier holds is configs/data_artifacts.toml: every entry is a
DataArtifacts `tree` (its `mount_dir`, `dir` and `filter`), read from the
author's data root (data_root(): VGTK_DATA_ROOT, or the data/exp_raw link) in
the published layout. The packing is VisualGeometryToolkitEval's
DataArtifacts.pack_artifacts — the stack's one packer: each tier's tree built in
a scratch artifacts directory under `--stage` (never the depot), archived to
<stage>/tarballs/<name>.tar.gz, and bound lazily in Artifacts.toml with its
git-tree-sha1, the tarball's sha256 and its record's URL. A staged tarball whose
file listing is current is reused.

Before packing, the author's tree is in the published layout and the current
schemas:
  - a copied file whose schema has a migration (a board's blobboards/board/v1–v4,
    a camera store's vgio/cameras/v3, any kind VisualGeometryToolkitIO or
    BlobBoards migrates) is migrated once, on the author's tree, by
    VisualGeometryToolkitIO.vgio_migrate_tree (every record read back and
    compared; a board's stored hashes.config — its uid — carried over);
  - the inputs tier's camera of record (<session>/calibration/<camera>.json) is
    scripts/import_cameras.jl's output, and its provenance/ material (the
    BlobBoards-Evaluation code archive, the upstream calibration exports, the
    README) sits under absolute_pose_experiments/provenance/, as published.
The published records (1.3.0 and the images record) reproduce from such a tree
byte for byte: the catalog's file lists give each binding's git-tree-sha1.

`--record=<group>=<id>` names a record's Zenodo id (or Hugging Face revision)
for the URLs (the rebind after a deposit is published); without it the
catalog's `id`, else its placeholder, which fetch_data.jl refuses to download.
Since data record 1.3.0 the images tier is its own record (`bb_images`,
23965208). A new dataset version is a new record id and a rebind here, never a
mutation.
=#

using DrWatson
@quickactivate  # activates bmvc2026 from this file's location (DrWatson layout)
using VisualGeometryToolkitEval: cli_option
using VisualGeometryToolkitEval.DataArtifacts: project_catalog, pack_artifacts

const CATALOG = project_catalog()
const STAGE = cli_option(ARGS, "stage")
const ONLY = filter(!isempty, split(cli_option(ARGS, "only", ""), ','))
const RECORD_IDS = Dict(String(first(kv)) => String(last(kv))
    for kv in (split(r, '='; limit = 2) for r in split(cli_option(ARGS, "record", ""), ',') if !isempty(r)))

built = pack_artifacts(CATALOG, isempty(ONLY) ? sort(collect(keys(CATALOG.artifacts))) : String.(ONLY);
    stage = STAGE, record_ids = RECORD_IDS)
for b in built
    println(rpad(b.name, 40), " tree ", bytes2hex(b.hash.bytes), "  ", round(b.bytes / 2^20; digits = 1), " MiB  sha256 ", b.sha)
end
println("Artifacts.toml: $(CATALOG.artifacts_toml)")
println("DONE")
