#=
flip_table.jl — the paper table: planar-pose flips per marker system, and
the share BlobBoards recovers with mirror + symmetric-LRT disambiguation.

A "flip" is a detection whose rotation error against the motion-capture
ground truth exceeds 10°: the two-fold planar-pose ambiguity puts the
secondary mode near twice the viewing obliqueness, and the >10° threshold
sits in the gap of the bimodal distribution, so the count is
threshold-robust.

All three systems are censused identically (same rig join, same per-system
hand-eye calibration, same threshold). AprilTag and ArUco resolve the
ambiguity inside their own detectors and expose no mechanism to revisit it,
so their "corrected" entry is empty by construction — BlobBoards is the only
system here that can revisit the branch, which is the point of the table.

For BlobBoards the census runs TWICE over pose sets that differ only in the
branch decision (identical detections, identical correspondences, identical
calibration): the `flip_base` series (the no-disambiguation sweep,
configs/bmvc2026_260527_noflip.toml: the RANSAC winner) and `bb` (reflect the
winner, refine both branches with the same seeded LO on the same
measurements, keep the higher likelihood). The delta isolates the method.
Both are read from their keyed runs (evaluation.toml `[runs]`, src/runs.jl).

Writes plotsdir()/flip_table.tex

Usage:
  julia --startup-file=no --project=bmvc2026 bmvc2026/scripts/flip_table.jl
=#
# reproduce: reads configs/figures/evaluation.toml

using DrWatson
@quickactivate  # activates bmvc2026 from this file's location (DrWatson layout)

include(joinpath(@__DIR__, "..", "src", "BlobBoardsEval.jl"))
using .BlobBoardsEval
using .BlobBoardsEval: rig_sequence, load_detected_poses, pose_error_table, hand_eye,
    detected_marker_sizes, static_recovery_accepted, figure_config, write_figure_records, eval_sources, poses_dir
using VisualGeometryToolkitEval.Experiments: Stage, run_stages
using DrWatson: plotsdir, projectdir
using Statistics

const EVAL, EVAL_PATH = figure_config("evaluation"; default = projectdir("configs", "figures", "evaluation.toml"))
const DRV = EVAL["drivers"]
const SRC = eval_sources(EVAL)
const flip_deg = Float64(DRV["flip_deg"])
const base_set = String(DRV["flip_base"])


# Per-system census. `series` names the detections censused (a series of the
# sources); the rig join, the board definitions and the hand-eye calibration
# are `name`'s, so BlobBoards is censused twice (with and without the branch
# decision) against the very same calibration and rig join.
function census(name, abbr; series = name)
    frames = rig_sequence(SRC.mocap, abbr)
    detected = load_detected_poses(poses_dir(SRC, series))

    marker_sizes = detected_marker_sizes(SRC.inputs, abbr, load_detected_poses(poses_dir(SRC, name)))

    # The calibration rig sequence carries the static-camera recovery (the
    # camera-rig trajectory's `recovered` frames), the same frames the pose
    # results use — one producer, so the two cannot disagree about it.
    static_recovered = static_recovery_accepted(SRC.mocap, "calibration_" * abbr)
    static_recovered || @warn "static-camera recovery was refused for calibration_$abbr; tracked frames only"
    calib_frames = rig_sequence(SRC.mocap, "calibration_" * abbr)
    calib_detected = load_detected_poses(poses_dir(SRC, name; calibration = true))

    # The ONE hand-eye authority, the same artifact the pose results resolve.
    he = hand_eye(calib_frames, calib_detected; dataset = SRC.dataset, subset = "calibration_" * abbr)
    df = pose_error_table(frames, detected, he.X, he.targets; marker_sizes)
    return map((1000, 2000, 3000)) do spot
        d = df[df.rig_distances_bin .== spot, :]
        a = abs.(collect(skipmissing(d.abs_error_angles_deg)))
        (n = length(a), flips = count(>(flip_deg), a))
    end
end

function main()
    bb_base = census("bb", "bb"; series = base_set)
    bb_lrt = census("bb", "bb")
    apr = census("apriltags", "apr")
    uco = census("aruco", "uco")

    _tot(c) = sum(r.flips for r in c)

    # Methods across, distances down: every column is a branch decision that some
    # mechanism already made, so there is no "corrected" column implying the tag
    # solvers make none — IPPE chooses too, it just does not report the choice.
    cols = [("AprilTag", apr), ("ArUco", uco),
        ("BlobBoards", bb_base), ("BlobBoards+LRT", bb_lrt)]
    _line(label, f) = "$(label) & " * join((string(f(c)) for (_, c) in cols), " & ") * " \\\\"

    io = IOBuffer()
    println(io, "% flip_table.tex — generated by bmvc2026/scripts/flip_table.jl; do not edit by hand")
    println(io, "\\setlength{\\tabcolsep}{10pt}")
    println(io, "\\begin{tabular}{@{}l" * "c"^length(cols) * "@{}}")
    println(io, "\\toprule")
    println(io, "flips (\$>$(round(Int, flip_deg))^\\circ\$) & " *
                join(("\\multicolumn{1}{c}{$(n)}" for (n, _) in cols), " & ") * " \\\\")
    println(io, "\\midrule")
    for (k, d) in enumerate(("\$1\\,\\mathrm{m}\$", "\$2\\,\\mathrm{m}\$", "\$3\\,\\mathrm{m}\$"))
        println(io, _line(d, c -> c[k].flips))
    end
    println(io, "\\midrule")
    println(io, _line("total", _tot))
    println(io, "\\bottomrule")
    println(io, "\\end{tabular}")

    # plotsdir(): derived product of this project, not of the dataset. The old
    # path also had no mkpath, so it threw whenever <dataset>/figures did not
    # already exist.
    outpath = plotsdir("flip_table.tex")
    mkpath(dirname(outpath))
    open(outpath, "w") do f
        write(f, take!(io))
    end
    println("flip_table.tex -> $outpath")

    # Prose macros so the counts the paper cites in text are the same ones the
    # table plots — never a second hand-typed copy that can drift from it.
    statpath = plotsdir("flip_stats.tex")
    open(statpath, "w") do f
        println(f, "% flip_stats.tex — generated by flip_table.jl; do not edit by hand")
        println(f, "\\newcommand{\\flipApr}{$(_tot(apr))}")
        println(f, "\\newcommand{\\flipUco}{$(_tot(uco))}")
        println(f, "\\newcommand{\\flipBBraw}{$(_tot(bb_base))}")
        println(f, "\\newcommand{\\flipBBlrt}{$(_tot(bb_lrt))}")
        println(f, "\\newcommand{\\flipBBcorrected}{$(_tot(bb_base) - _tot(bb_lrt))}")
    end
    println("flip_stats.tex -> $statpath")
    for (lbl, c) in (("AprilTag", apr), ("ArUco", uco), ("BB (no LRT)", bb_base), ("BB (+LRT)", bb_lrt))
        println("  $lbl: n=$(sum(r.n for r in c))  flips=$([r.flips for r in c])  total=$(_tot(c))")
    end
    write_figure_records(EVAL, EVAL_PATH; driver = "bmvc2026/scripts/flip_table.jl", inputs = [poses_dir(SRC, s) for s in ("apriltags", "aruco", "bb", base_set)], outputs = [outpath, statpath])
    return nothing
end

run_stages("flip_table", [Stage(:emit, "flip_table.tex + flip_stats.tex: planar-pose flips per marker system", () -> false, main)])
