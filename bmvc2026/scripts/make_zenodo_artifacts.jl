#=
make_zenodo_artifacts.jl — package the absolute-pose experiments into Julia
artifacts for Zenodo hosting.

  julia --project=bmvc2026 bmvc2026/scripts/make_zenodo_artifacts.jl \
        [tier] [staging_dir] [zenodo_record_id]

ONLY INPUTS are published: measurements and what no code of ours produces.
Every result (detections, motion-capture records, hand-eye fits, pose-error
cells, overlays) is regenerated by regenerate_paper.jl into results_root()
(src/runs.jl), so no tier carries one.

Tiers:
  inputs     (~10 MB) bb_absolute_pose_inputs: per published session the raw
             motion-capture exports (poses/motion_tracker/<subset>/marker_*.json,
             the operator-rejected `.json.del` frames included), the camera of
             record (calibration/<camera>.json, vgio/cameras/v3 — the output
             of scripts/import_cameras.jl, found through its config of
             record), the board definitions (boards/, without the generator's
             `_tmp.png` byproducts); the teaser photos (teaser/); and the
             provenance material (provenance/): the BlobBoards-Evaluation code
             archive the baselines, the camera calibration and the occlusion
             images come from, and the upstream calibration export each
             camera of record was ported from.
  images     (~8 GB)  260527/images — the captures (raw measurements).
  occlusion  (~39 GB) occlusion/<NN>/images per-level tarballs (lazy): the
             synthetic occlusion images, inputs with provenance (generated by
             BlobBoards-Evaluation 88bca9f evaluation_pipe/occlusion_generator.py).
  assets     evaluation/blobboards_original (the 50-board gallery,
             DEFINITIONS only — renders regenerate from the recorded blob
             lists) and models/*.onnx (the descriptor networks) from the
             DATASET ROOT (the parent of absolute_pose_experiments/). These
             are inputs of the Fig. 1 teaser (make_bmvc2026_intro.jl) and the
             adapted panels (make_adapted_panels.jl); before this tier they
             shipped in NO artifact, so those figures were unreproducible
             from the published record. Cache .jld2 files stay excluded —
             BoardGallery re-derives them from boards + network.
  training   descriptor_training/ from the DATASET ROOT — the frozen
             descriptor training set (Sec. "Curriculum training"): two
             tiers, so the recipe is fetchable without the footage.
               bb_descriptor_training_metadata (~150 MB) — the 50 training
                 board definitions, the bootstrap network chain
                 (bootstrap_synthetic, bootstrap_real_iteration_{1,2,3}:
                 cfg.yaml, training.log, checkpoints/best.{onnx,pth}), the
                 build_tracks SLURM logs, and the README with the recipe.
               bb_descriptor_training_sources (~14 GB) — the 634 captures
                 (photos + videos) the tracks are cut from.
             The .tracks files themselves (3-13 GB each) are DERIVED and
             not shipped: the README's recipe regenerates them from
             sources + boards + the previous iteration's best.onnx.


Each artifact is content-addressed: the Artifacts.toml entry records the
git-tree-sha1 of the unpacked tree and the sha256 of the tarball. Zenodo
records are immutable with stable file URLs, which is exactly the artifact
contract — publishing a new dataset version means a new record id and a
rebind here, never mutation.

Run without a record id to stage tarballs + bind with a placeholder URL;
rerun with the id after the Zenodo deposit is published to fix the URLs
(tarballs are NOT rebuilt if already staged — hashes are reused).
=#

using DrWatson
@quickactivate  # activates bmvc2026 from this file's location (DrWatson layout)
using Pkg.Artifacts
using SHA
using TOML

# This driver lives in <subproject>/scripts/, but the Artifacts.toml it binds
# into is the one src/data.jl reads — <subproject>/Artifacts.toml, one level
# up. Bind against @__DIR__ and the packager writes a file nothing consumes.
const PROJECT_ROOT = dirname(@__DIR__)

# The SOURCE copy is named explicitly (ENV["CAU_DATA_ROOT"], rung 1 of the
# data_root() ladder): the packer builds the artifacts, so it cannot resolve
# through the artifact view they define. Only the inputs tier loads
# BlobBoardsEval, to find the camera port's run through its config of record.
const DS_ROOT = joinpath(
    get(() -> error("set CAU_DATA_ROOT to the dataset root (20251028_BlobBoards_Office)"), ENV, "CAU_DATA_ROOT"),
    "absolute_pose_experiments"
)
const TIER = isempty(ARGS) ? "inputs" : ARGS[1]
const STAGE = length(ARGS) >= 2 ? ARGS[2] : joinpath(homedir(), "zenodo_staging_bb")
const RECORD = length(ARGS) >= 3 ? ARGS[3] : "ZENODO_RECORD_ID"
const ARTIFACTS_TOML = normpath(joinpath(PROJECT_ROOT, "Artifacts.toml"))

mkpath(STAGE)

_zenodo_url(name) = "https://zenodo.org/records/$RECORD/files/$name.tar.gz?download=1"

# Copy the files selected by `pred(relpath)` into an artifact tree, archive,
# and bind. Reuses an existing staged tarball (hash recomputed from it) so a
# record-id rerun doesn't repackage gigabytes.
function package!(name::String, roots::Vector{String}, pred; base_root::String = DS_ROOT)
    tarball = joinpath(STAGE, name * ".tar.gz")
    hash = create_artifact() do dir
        n = 0
        for root in roots
            base = joinpath(base_root, root)
            isdir(base) || continue
            for (r, _, files) in walkdir(base), f in files
                rel = relpath(joinpath(r, f), base_root)
                pred(rel) || continue
                dst = joinpath(dir, rel)
                mkpath(dirname(dst))
                cp(joinpath(base_root, rel), dst)
                n += 1
            end
        end
        println("  $name: $n files")
    end
    # Reuse is CONTENT-CHECKED (2026-08-11): a `.tree` sidecar records which
    # tree the staged tarball archives, and reuse requires a match. The bare
    # `isfile` reuse could bind a FRESH tree hash to a STALE archive after
    # any dataset change — a tarball whose unpacked tree can never match its
    # recorded git-tree-sha1, i.e. a hard install failure for every consumer,
    # discovered only after publication.
    treefile = tarball * ".tree"
    fresh = bytes2hex(hash.bytes)
    if !(isfile(tarball) && isfile(treefile) && strip(read(treefile, String)) == fresh)
        archive_artifact(hash, tarball)
        write(treefile, fresh)
    end
    sha = bytes2hex(open(sha256, tarball))
    bind_artifact!(
        ARTIFACTS_TOML, name, hash;
        download_info = [(_zenodo_url(name), sha)], lazy = true, force = true
    )
    sz = round(filesize(tarball) / 2^20; digits = 1)
    println("  $name: tree $hash, tarball $(sz) MiB, sha256 $sha")
    return nothing
end

# Package an explicit list of `source => tier-relative path` files (+ an
# optional provenance README) into one artifact, archive and bind it.
function package_files!(name::String, files::Vector{Pair{String, String}}; readme::String = "")
    tarball = joinpath(STAGE, name * ".tar.gz")
    allunique(last.(files)) || error("$name: two files map to one tier path")
    hash = create_artifact() do dir
        for (src, rel) in files
            dst = joinpath(dir, rel)
            mkpath(dirname(dst))
            cp(src, dst)
        end
        isempty(readme) || write(joinpath(dir, "provenance", "README.md"), readme)
        println("  $name: $(length(files)) files")
    end
    treefile = tarball * ".tree"
    fresh = bytes2hex(hash.bytes)
    if !(isfile(tarball) && isfile(treefile) && strip(read(treefile, String)) == fresh)
        archive_artifact(hash, tarball)
        write(treefile, fresh)
    end
    sha = bytes2hex(open(sha256, tarball))
    bind_artifact!(ARTIFACTS_TOML, name, hash; download_info = [(_zenodo_url(name), sha)], lazy = true, force = true)
    println("  $name: tree $hash, tarball $(round(filesize(tarball) / 2^20; digits = 1)) MiB, sha256 $sha")
    return nothing
end

# The sessions the record publishes. 260521 is excluded: it fails end-to-end
# validation (hand-eye self-residual ~11.7° under BOTH mocap matrix layouts —
# pairing or frame convention unresolved, see 2026-08-06 investigation).
const PUBLISHED_SESSIONS = ["260527"]

const PROVENANCE_README = """
# Provenance material of the BlobBoards absolute-pose inputs

Not inputs of any computation: the record of where three kinds of inputs came from.

- `BlobBoards-Evaluation-main.zip` — a snapshot (commit 88bca9f, 2026-05-29) of
  the external evaluation code (Till Sittart, BlobBoards-Evaluation). It holds
  the AprilTag/ArUco pose extraction (`evaluation_pipe/pose_extractor.py`,
  `pose_estimators.py`), ported faithfully to
  `bmvc2026/scripts/baselines/detect_markers.py`, which regenerates the
  published baseline poses bit for bit (they were produced on 2026-05-29 at
  77d3ddd, whose pose code differs from the snapshot's only by refactoring);
  the intrinsic calibration
  (`pose_estimators/calibrate_camera.py`, `calibrate_pinhole`) that produced the
  cameras; and the synthetic occlusion generator
  (`evaluation_pipe/occlusion_generator.py`: hand-clicked board corners, a MAGSAC
  homography per board) that produced the occlusion images.
- `calibration/<session>/<file>.json` — the upstream `calibrate_pinhole` export
  of each session's camera (OpenCV `calibrateCamera` on a 6×7 chessboard of
  0.05 m squares, CALIB_RATIONAL_MODEL with k3–k6 fixed; `reprojection_error`
  is a MEAN per-image error, not an RMS). The camera of record,
  `<session>/calibration/<file>.json` (vgio/cameras/v3), is its exact port by
  `bmvc2026/scripts/import_cameras.jl` (K and lens bit for bit; the principal
  point moved from OpenCV's pixel frame to the canonical one).
"""

_is_cache(rel) = endswith(rel, ".jld2")

if TIER == "inputs"
    # The inputs tier is assembled from several roots: the dataset (raw mocap,
    # boards, teaser photos, the code archive), the one-time camera port
    # (scripts/import_cameras.jl's run directory, derived from its config of
    # record) and the upstream calibration exports it ported (the config names
    # each by path and sha256).
    isdefined(Main, :BlobBoardsEval) || include(joinpath(PROJECT_ROOT, "src", "BlobBoardsEval.jl"))
    BBE = Main.BlobBoardsEval
    cams = BBE.load_config("import_cameras.toml")
    cam_run = BBE.run_dir("import_cameras", BBE.config_run_key(cams))
    isfile(joinpath(cam_run, "_provenance.toml")) || error("$(cam_run): run scripts/import_cameras.jl first")
    files = Pair{String, String}[]
    for session in PUBLISHED_SESSIONS
        mt = joinpath(DS_ROOT, session, "poses", "motion_tracker")
        for (r, _, fs) in walkdir(mt), f in fs
            (startswith(f, "marker_") && (endswith(f, ".json") || endswith(f, ".json.del"))) || continue
            push!(files, joinpath(r, f) => relpath(joinpath(r, f), DS_ROOT))
        end
        for (r, _, fs) in walkdir(joinpath(DS_ROOT, session, "boards")), f in fs
            endswith(f, "_tmp.png") && continue
            push!(files, joinpath(r, f) => relpath(joinpath(r, f), DS_ROOT))
        end
        for c in cams["cameras"]
            c["session"] == session || continue
            push!(files, joinpath(cam_run, session, "calibration", c["output"]) => joinpath(session, "calibration", c["output"]))
            src = c["source"]
            bytes2hex(open(sha256, src)) == c["sha256"] || error("$(src): sha256 differs from the config of record")
            push!(files, src => joinpath("provenance", "calibration", session, basename(src)))
        end
    end
    for f in ("DSC04596.png", "testit.jpg")
        push!(files, joinpath(DS_ROOT, "teaser", f) => joinpath("teaser", f))
    end
    push!(files, joinpath(DS_ROOT, "BlobBoards-Evaluation-main.zip") => joinpath("provenance", "BlobBoards-Evaluation-main.zip"))
    package_files!("bb_absolute_pose_inputs", files; readme = PROVENANCE_README)
elseif TIER == "images"
    package!("bb_absolute_pose_images_260527", ["260527/images"], rel -> true)
elseif TIER == "occlusion"
    for lvl in filter(
            l -> isdir(joinpath(DS_ROOT, "260527", "occlusion", l)),
            sort(readdir(joinpath(DS_ROOT, "260527", "occlusion")))
        )
        package!(
            "bb_absolute_pose_occlusion_$(lvl)_260527",
            ["260527/occlusion/$lvl/images"], rel -> true
        )
    end
elseif TIER == "assets"
    # DATASET-ROOT tier (see the header): the board gallery + the descriptor
    # networks the teaser/panel figures read. Placed at the VIEW ROOT by
    # `_artifact_view` (every other tier mounts under
    # absolute_pose_experiments/), so `data_root()/evaluation/...` and
    # `data_root()/models/...` resolve identically on primary copy and
    # artifact view. Caches (.jld2) excluded — BoardGallery re-derives them.
    # models/ carries the whole training lineage (~880 MB of retired
    # blob_matcher_* generations); the record ships only the network(s) OF
    # RECORD — the config-of-record iter4 export, plus the `_cuda` export the
    # pre-iter4 promoted runs cite in their sidecars. Caches (.jld2) stay
    # excluded — BoardGallery re-derives them from boards + network.
    _record_model(rel) = first(splitpath(rel)) != "models" ||
        basename(rel) in (
        "track_logpolar_circ_s96_iter4.onnx",
        "track_logpolar_circ_s96_cuda.onnx",
    )
    # Board DEFINITIONS only (JSON): renders regenerate on demand from the
    # recorded blob lists (BlobBoards.render_board, 0.18.0 — geometrically
    # exact; radiometrically a one-pixel perimeter ring + <=2/255 ink
    # quantization against the print-run renders, from the 2026-07-28
    # rasterizer change). The paper's numbers do not depend on regeneration:
    # the promoted poses and the gallery feature cache ship in the metadata
    # tier. Dropping PDF+PNG cuts this tier ~300 MB, mirroring the HF
    # examples artifact (definitions-only since 2026-08-20).
    _definition_only(rel) =
        first(splitpath(rel)) != "evaluation" || endswith(rel, ".json")
    package!(
        "bb_assets", ["evaluation/blobboards_original", "models"],
        rel -> !_is_cache(rel) && _record_model(rel) && _definition_only(rel);
        base_root = dirname(DS_ROOT)
    )
elseif TIER == "training"
    # DATASET-ROOT tier pair (see the header). Placed at the view root like
    # bb_assets, so `data_root()/descriptor_training/...` resolves identically
    # on primary copy and artifact view. The primary copy is an rsync of
    # the frozen `BlobBoardTrainingFootage/final/` training footage (2026-08-28):
    # sources/ verbatim; blobboards_original/ JSON only (byte-identical to
    # evaluation/blobboards_original, shipped again so the tier is
    # self-contained); networks/ without latest.pth and the loss plots.
    _training_meta(rel) = first(splitpath(rel)) == "descriptor_training" &&
        splitpath(rel)[2] != "sources"
    package!(
        "bb_descriptor_training_metadata", ["descriptor_training"],
        rel -> _training_meta(rel) && !_is_cache(rel);
        base_root = dirname(DS_ROOT)
    )
    package!(
        "bb_descriptor_training_sources", ["descriptor_training/sources"],
        rel -> true;
        base_root = dirname(DS_ROOT)
    )
else
    error("unknown tier $TIER (inputs | images | occlusion | assets | training)")
end

println("Artifacts.toml: $ARTIFACTS_TOML (record id: $RECORD)")
println("DONE")
